def advanced_rows(key: str) -> list[tuple[str, str]]:
    """返回指定配置册的高级版说明行（公共 + 本册专属）。"""
    return ADVANCED_GUIDES["_common"] + ADVANCED_GUIDES.get(key, [])


def guide_rows(key: str) -> list[tuple[str, str]]:
    """返回指定配置册的说明行（不含版本行）。"""
    return GUIDES[key][1]


def guide_title(key: str) -> str:
    return GUIDES[key][0]


def write_guide_sheet(book, key: str, *, index: int = 0):
    """在已打开的工作簿中重建“使用说明”表并返回该表。

    ``index=0`` 让说明表排在最前，用户打开工作簿先看到维护指引。
    """
    from openpyxl.styles import Alignment, Font, PatternFill

    if key not in GUIDES:
        raise KeyError(f"未知配置册：{key}")
    if GUIDE_SHEET in book.sheetnames:
        del book[GUIDE_SHEET]
    sheet = book.create_sheet(GUIDE_SHEET, index)

    header_font = Font(bold=True, color="FFFFFF")
    header_fill = PatternFill("solid", fgColor="1F4E78")
    item_font = Font(bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")

    # Excel 内只保留「用途与配置维护」；按钮操作步骤与高级开关
    # 写入两份 docx（tools/build_system_operation_guides.py 生成）。
    sheet.append([VERSION_ITEM, CONFIG_VERSION])
    sheet.append([BO_REMARK_ITEM, "操作步骤见《基础数据审核工具使用说明.docx》（简易版）；"
                  "高级开关见《…_高级版.docx》"])
    sheet.append([])
    for item, description in guide_rows(key):
        sheet.append([item, description])
    for cell in sheet[1]:
        cell.font = header_font
        cell.fill = header_fill
    for row in sheet.iter_rows(min_row=3):
        row[0].font = item_font
        row[1].alignment = wrap
    sheet.column_dimensions["A"].width = 24
    sheet.column_dimensions["B"].width = 100
    return sheet


def read_config_version(path: Path | str | None) -> str:
    """读取配置工作簿“使用说明”首行的版本号；缺失或损坏返回空串。"""
    target = Path(path) if path else None
    if target is None or not target.is_file():
        return ""
    from openpyxl import load_workbook

    try:
        book = load_workbook(target, read_only=True, data_only=True)
    except Exception:
        return ""
    try:
        if GUIDE_SHEET not in book.sheetnames:
            return ""
        for row in book[GUIDE_SHEET].iter_rows(max_row=4, values_only=True):
            if row and str(row[0] or "").strip() == VERSION_ITEM:
                return str(row[1] or "").strip()
        return ""
    finally:
        book.close()


def write_guide_to_file(path: Path | str, key: str) -> bool:
    """给已存在的配置工作簿就地补齐/刷新“使用说明”；返回是否写入。

    工作簿缺失、损坏或版本已是最新时返回 False（调用方据此决定是否提示重置）。
    """
    from openpyxl import load_workbook

    target = Path(path)
    if not target.is_file() or read_config_version(target) == CONFIG_VERSION:
        return False
    try:
        book = load_workbook(target)
    except Exception:
        return False  # 已损坏：交给上层提示用户去设置中心重置
    try:
        write_guide_sheet(book, key)
        temporary = target.with_name(target.stem + ".tmp.xlsx")
        book.save(temporary)
        temporary.replace(target)
    except PermissionError as exc:
        raise RuntimeError(f"无法更新“{target.name}”的使用说明：请先关闭该文件后重试") from exc
    finally:
        book.close()
    return True
